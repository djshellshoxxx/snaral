#!/usr/bin/env python3
"""Generate docs/release/WIRING.md: parameter id -> DSP consumer table.

Source of truth for the parameter list is Source/Parameters/Groups/*.def (the same files ParameterTable.h expands).
A "consumer" is a reference to P::<id> in Source/Engine, Source/Dsp, Source/PluginProcessor.cpp. Parameters with a trailing
number (traj_x1..) also count as consumed when P::<prefix>1 is referenced (indexed as P::<prefix>1 + k). Registry,
state and CC-learn code are generic table walkers and are not counted as DSP consumers.

Usage: tools/gen_wiring.py [--check]   (--check exits 1 if any parameter has no DSP consumer)
"""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
decl = re.compile(r'^\s*SNARAL_(FLOAT|CHOICE|BOOL|INT)\w*\s*\(\s*(\w+)\s*,\s*"([^"]*)"\s*,\s*"([^"]*)"')

params = []
for f in sorted((root / "Source/Parameters/Groups").glob("*.def")):
    for line in f.read_text().splitlines():
        m = decl.match(line)
        if m:
            params.append((m.group(2), m.group(3), m.group(4), f.stem))

scan_dirs = [root / "Source/Engine", root / "Source/Dsp"]
scan_files = [root / "Source/PluginProcessor.cpp"]
sources = []
for d in scan_dirs:
    sources += [p for p in d.rglob("*") if p.suffix in (".h", ".cpp")]
sources += scan_files
texts = {p: p.read_text(errors="replace") for p in sources}


def users(pid):
    pat = re.compile(r'\bP::' + re.escape(pid) + r'\b')
    return sorted({str(p.relative_to(root / "Source")) for p, t in texts.items() if pat.search(t)})


rows, missing = [], []
for pid, name, group, defn in params:
    u = users(pid)
    note = ""
    if not u:
        m = re.match(r'^(.*?)(\d+)$', pid)
        if m:
            u = users(m.group(1) + "1")
            if u:
                note = " (indexed range)"
    if not u:
        missing.append(pid)
    rows.append((pid, name, group, u, note))

out = ["# Wiring status: parameter id to DSP consumer", "",
       "Generated by `tools/gen_wiring.py` from `Source/Parameters/Groups/*.def` plus a search of `Source/Engine`, "
       "`Source/Dsp` and `Source/PluginProcessor.cpp` for `P::<id>`. Do not edit by hand.", "",
       f"Parameters: {len(rows)}. Without a DSP consumer: {len(missing)}.", ""]
if missing:
    out += ["## Parameters with NO DSP consumer", ""] + [f"- `{p}`" for p in missing] + [""]
else:
    out += ["Every registered parameter is referenced by at least one DSP or engine source.", ""]
out += ["Note: a reference proves the value is read, not that it is audible or correct; behaviour is covered by the tests in `tests/`.", "",
        "## Table", "", "| Parameter id | Name | Group | Consumer(s) | Status |", "|---|---|---|---|---|"]
for pid, name, group, u, note in rows:
    status = "NO CONSUMER" if not u else "wired" + note
    out.append(f"| `{pid}` | {name} | {group} | {', '.join(f'`{x}`' for x in u) or '-'} | {status} |")
dest = root / "docs/release/WIRING.md"
dest.parent.mkdir(parents=True, exist_ok=True)
dest.write_text("\n".join(out) + "\n")
print(f"{len(rows)} parameters, {len(missing)} without consumer -> {dest.relative_to(root)}")
for p in missing:
    print("  no consumer:", p)
if "--check" in sys.argv and missing:
    sys.exit(1)
